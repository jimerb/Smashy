export function puzzleCells(index: number, profile: Profile): Cell[] {
  const puzzle = PUZZLES[index];
  if (!puzzle || !puzzle.variants[profile])
    throw new Error("Unknown puzzle or layout.");
  const cells: Cell[] = [];
  puzzle.variants[profile].rows.forEach((line, row) =>
    [...line].forEach((character, col) => {
      if (character === ".") return;
      if (!"0123456#".includes(character))
        throw new Error("Invalid authored puzzle character.");
      cells.push({
        row,
        col,
        type: (character === "#" ? 7 : Number(character)) as PieceType,
      });
    }),
  );
  return cells;
}
export function puzzleGame(
  index: number,
  profile: Profile,
  assisted = false,
): GameState {
  const puzzle = PUZZLES[index];
  if (!puzzle || !puzzle.variants[profile])
    throw new Error("Unknown puzzle or layout.");
  const variant = puzzle.variants[profile];
  return createGame({
    config: { ...getConfig("standard", profile), target: puzzle.target },
    seed: variant.seed,
    board: puzzleCells(index, profile),
    current: variant.current,
    next: variant.next,
    assisted,
  });
}
